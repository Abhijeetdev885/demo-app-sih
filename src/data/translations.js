export function t(lang, key) {
  const table = translations[lang] || translations.en
  const parts = key.split('.')
  let value = table
  for (const part of parts) {
    value = value?.[part]
  }
  if (value === undefined) {
    value = translations.en
    for (const part of parts) {
      value = value?.[part]
    }
  }
  return value ?? key
}
